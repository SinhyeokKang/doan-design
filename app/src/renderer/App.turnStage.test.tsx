test("a pushed stage reaches the Overview thread's turn indicator through App", async () => {
  doan.listConversations = vi.fn(async () => [summary]);
  doan.readConversation = vi.fn(async () => ({ events: [at(1, { type: "user.message", text: "Draw the checkout", anchors: [] }), at(2, { type: "turn.started" })], lastSeq: 2, turn: "running" }));
  render(); folders([listed("/w/a")]);
  find<{ worktree(root: string): void }>(ShellSidebar)[0]!.props.worktree("/w/a"); render();
  await flushAll();
  const { run } = find<ProjectOverviewProps>(ProjectOverview)[0]!.props;
  run.select("/w/a", A); render();
  run.store.track(A);
  await flushAll();
  expect(doan.onConversationStage).toHaveBeenCalledOnce();
  expect(overviewHtml()).toContain('<span class="ti-text ti-shimmer">Claude Code is working</span>');
  const thinking: StageSignal = { conversationId: A, turnId: "t1", seq: 2, rev: 1, stage: { kind: "thinking" } };
  (listeners.stage as (signal: StageSignal) => void)(thinking); render();
  expect(run.store.stageOf(A)).toBe(thinking);
  expect(overviewHtml()).toContain('<span class="ti-text ti-shimmer">Claude Code is thinking</span>');
});
